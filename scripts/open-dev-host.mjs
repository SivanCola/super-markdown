import { existsSync, mkdirSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { spawn, spawnSync } from "node:child_process";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const devDir = join(root, ".dev");
const testFile = join(devDir, "super-markdown-test.md");
const userDataDir = join(devDir, "vscode-user-data");
const extensionsDir = join(devDir, "vscode-extensions");

mkdirSync(devDir, { recursive: true });
mkdirSync(userDataDir, { recursive: true });
mkdirSync(extensionsDir, { recursive: true });

writeFileSync(testFile, buildTestMarkdown(), "utf8");

run("npm", ["run", "compile"]);

const codeBin = findCodeBinary();
const args = [
  "--new-window",
  `--extensionDevelopmentPath=${root}`,
  `--user-data-dir=${userDataDir}`,
  `--extensions-dir=${extensionsDir}`,
  testFile
];

console.log(`Opening VS Code Extension Development Host with ${testFile}`);
const child = spawn(codeBin, args, {
  cwd: root,
  detached: true,
  stdio: "ignore",
  shell: process.platform === "win32"
});
child.unref();

function run(command, args) {
  const result = spawnSync(command, args, {
    cwd: root,
    stdio: "inherit",
    shell: process.platform === "win32"
  });
  if (result.status !== 0) {
    process.exit(result.status ?? 1);
  }
}

function findCodeBinary() {
  const candidates = [
    process.env.VSCODE_BIN,
    "code",
    "code-insiders",
    "/Applications/Visual Studio Code.app/Contents/Resources/app/bin/code",
    "/Applications/Visual Studio Code - Insiders.app/Contents/Resources/app/bin/code"
  ].filter(Boolean);

  for (const candidate of candidates) {
    const result = spawnSync(candidate, ["--version"], {
      cwd: root,
      encoding: "utf8",
      shell: process.platform === "win32"
    });
    if (result.status === 0) {
      return candidate;
    }
  }

  console.error("Could not find the VS Code CLI. Install the `code` command or set VSCODE_BIN.");
  process.exit(1);
}

