function assetPrefixFor(relativePath) {
  const dir = dirname(relativePath);
  const depth = dir === "." ? 0 : dir.split(/[\\/]+/).filter(Boolean).length;
  return Array.from({ length: depth + 1 }, () => "..").join("/");
}

